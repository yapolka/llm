FINAL_ANSWER_SYSTEM_PROMPT_TEMPLATE = """Ты — ассистент поддержки. {routing_instruction}

Отвечай ТОЛЬКО валидным JSON:
{{
  "final_answer": "финальный ответ пользователю"
}}
"""


def build_final_answer_prompt(text, summary, key_points, sentiment, urgency):
    points_str = "; ".join(key_points)
    return f"""Составь финальный ответ пользователю на основе анализа:

Исходный текст: \"\"\"{text}\"\"\"
Краткое содержание: {summary}
Ключевые моменты: {points_str}
Тональность: {sentiment}
Срочность: {urgency}
"""


